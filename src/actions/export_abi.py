import os
import json
import glob
from .common import get_contracts_dir

def _find_contract_artifact(contract_name, candidate_dirs):
    """
    Finds the compiled artifact JSON file for a given contract.
    Searches Hardhat and Foundry output patterns.
    """
    for base_dir in candidate_dirs:
        if not base_dir or not os.path.exists(base_dir):
            continue

        # Pattern 1: Hardhat: **/ContractName.sol/ContractName.json
        matches = glob.glob(os.path.join(base_dir, "**", f"{contract_name}.json"), recursive=True)
        # Filter out .dbg.json metadata files generated by Hardhat
        valid_matches = [m for m in matches if not m.endswith(".dbg.json")]
        if valid_matches:
            return valid_matches[0]

        # Pattern 2: Direct file match
        direct = os.path.join(base_dir, f"{contract_name}.json")
        if os.path.exists(direct):
            return direct

    return None

def export_abi(params, pipeline_path=None, deployed_contracts=None, networks_config=None):
    contract = params.get('contract')
    if not contract:
        print("  [❌] Missing required parameter 'contract' in export_abi action.")
        return {'status': 'failure', 'error': "Missing 'contract' parameter"}

    destination = params.get('destination', 'exports')
    include_bytecode = params.get('include_bytecode', False)
    generate_ts = params.get('typescript', True)
    network = params.get('network')
    address = params.get('address')

    # Resolve address from deployed_contracts if not explicitly given
    if not address and deployed_contracts and contract in deployed_contracts:
        address = deployed_contracts[contract]

    # Resolve destination path
    if not os.path.isabs(destination):
        base_dir = os.path.dirname(pipeline_path) if pipeline_path else os.getcwd()
        # If relative, place relative to project root or pipeline path
        project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
        dest_abs = os.path.abspath(os.path.join(project_root, destination))
    else:
        dest_abs = os.path.abspath(destination)

    os.makedirs(dest_abs, exist_ok=True)

    # Search paths for artifacts
    contracts_dir = get_contracts_dir(params)
    project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))

    candidate_dirs = [
        params.get('artifacts_dir'),
        os.path.join(project_root, "artifacts"),
        os.path.join(contracts_dir, "artifacts"),
        os.path.join(contracts_dir, "out"),  # Foundry
        os.path.join(project_root, "out"),
    ]

    artifact_file = _find_contract_artifact(contract, candidate_dirs)
    if not artifact_file:
        print(f"  [❌] Artifact file for contract '{contract}' not found in candidate directories.")
        return {'status': 'failure', 'error': f"Artifact for '{contract}' not found"}

    try:
        with open(artifact_file, 'r') as f:
            artifact_data = json.load(f)
    except Exception as e:
        print(f"  [❌] Error reading artifact file {artifact_file}: {e}")
        return {'status': 'failure', 'error': f"Failed to read artifact: {e}"}

    abi = artifact_data.get('abi', [])
    bytecode = artifact_data.get('bytecode')

    # 1. Export clean ABI JSON: <Contract>.abi.json
    abi_json_path = os.path.join(dest_abs, f"{contract}.abi.json")
    with open(abi_json_path, 'w') as f:
        json.dump(abi, f, indent=2)

    # 2. Export Full Deployment Package (if address is present or explicitly requested)
    full_export_path = None
    if address or network:
        pkg_filename = f"{contract}.{network}.json" if network else f"{contract}.deployment.json"
        full_export_path = os.path.join(dest_abs, pkg_filename)
        chain_id = None
        if networks_config and network and network in networks_config:
            chain_id = networks_config[network].get('chain_id')

        package_data = {
            "contract": contract,
            "address": address,
            "network": network,
            "chainId": chain_id,
            "abi": abi,
        }
        if include_bytecode and bytecode:
            package_data["bytecode"] = bytecode

        with open(full_export_path, 'w') as f:
            json.dump(package_data, f, indent=2)

    # 3. Export TypeScript module with `as const` (for Viem / Wagmi)
    ts_export_path = None
    if generate_ts:
        ts_export_path = os.path.join(dest_abs, f"{contract}.ts")
        abi_json_str = json.dumps(abi, indent=2)
        ts_lines = [
            f"// Generated by Web3 DevOps Toolkit",
            f"export const {contract}ABI = {abi_json_str} as const;",
            f"export type {contract}ABI = typeof {contract}ABI;",
        ]
        if address:
            ts_lines.append(f'export const {contract}Address = "{address}" as const;')
        if network:
            ts_lines.append(f'export const {contract}Network = "{network}" as const;')

        with open(ts_export_path, 'w') as f:
            f.write("\n".join(ts_lines) + "\n")

    print(f"  [📦] ABI exported successfully to {abi_json_path}")
    if ts_export_path:
        print(f"  [TypeScript] Typed ABI exported to {ts_export_path}")
    if full_export_path:
        print(f"  [Manifest] Deployment package exported to {full_export_path}")

    return {
        'status': 'success',
        'contract': contract,
        'abi_path': abi_json_path,
        'ts_path': ts_export_path,
        'deployment_path': full_export_path,
        'destination': dest_abs
    }
