import os
import json
from datetime import datetime, timezone

def safe_stage(params, pipeline_path=None, deployed_contracts=None, networks_config=None):
    """
    Stages transactions or contract deployments into a Gnosis Safe Transaction Batch JSON format,
    ready for multi-sig signers to import into app.safe.global Transaction Builder.
    """
    contract = params.get('contract')
    network = params.get('network', 'localhost')
    safe_address = params.get('safe_address', '0x0000000000000000000000000000000000000000')
    output_path = params.get('output', 'exports/safe-batch.json')
    transactions = params.get('transactions', [])

    chain_id = "1"
    if networks_config and network in networks_config:
        chain_id = str(networks_config[network].get('chain_id', "1"))

    # If no custom transactions provided, build a deployment placeholder or transfer call
    if not transactions and contract:
        target_addr = deployed_contracts.get(contract) if deployed_contracts else None
        transactions = [
            {
                "to": target_addr or safe_address,
                "value": "0",
                "data": params.get('calldata', "0x"),
                "contractMethod": params.get('method_signature'),
                "contractInputsValues": params.get('method_args')
            }
        ]

    # Build Gnosis Safe Transaction Builder standard JSON schema
    safe_batch = {
        "version": "1.0",
        "chainId": chain_id,
        "createdAt": int(datetime.now(timezone.utc).timestamp() * 1000),
        "meta": {
            "name": f"{contract or 'Web3'} Safe Transaction Batch",
            "description": f"Staged transaction batch generated by Web3 DevOps Toolkit for network '{network}'",
            "txBuilderVersion": "1.16.1",
            "createdFromSafeAddress": safe_address
        },
        "transactions": transactions
    }

    # Resolve output path
    project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
    if not os.path.isabs(output_path):
        target_abs = os.path.abspath(os.path.join(project_root, output_path))
    else:
        target_abs = os.path.abspath(output_path)

    os.makedirs(os.path.dirname(target_abs), exist_ok=True)
    with open(target_abs, 'w') as f:
        json.dump(safe_batch, f, indent=2)

    print(f"  [🛡️] Safe multi-sig transaction batch staged to: {target_abs}")
    return {
        'status': 'success',
        'safe_batch_file': target_abs,
        'chain_id': chain_id,
        'transactions_count': len(transactions)
    }
